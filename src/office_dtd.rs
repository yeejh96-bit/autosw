//! In-memory compatibility for XmlDocument's internal DTD defaults and entities.
//! No URI is opened. External parsed entities have the empty replacement used
//! by XmlDocument with its default disabled resolver. This is only for the
//! legacy PowerShell plain-text reader, never the strict structure/writer path.
use std::collections::{HashMap, HashSet};

const LIMIT: usize = 64 * 1024 * 1024;
const REFERENCES: usize = 100_000;
const DEPTH: usize = 64;
fn space(c: char) -> bool {
    matches!(c, ' ' | '\t' | '\r' | '\n')
}
fn error() -> String {
    "잘못되거나 지원하지 않는 XML DTD입니다.".into()
}
fn valid(c: char) -> bool {
    matches!(c as u32, 9|10|13|32..=0xd7ff|0xe000..=0xfffd|0x10000..=0x10ffff)
}
fn append(out: &mut String, value: &str) -> Result<(), String> {
    if out.len().saturating_add(value.len()) > LIMIT {
        return Err("XML 엔티티 전개 크기 한도를 넘었습니다.".into());
    }
    out.push_str(value);
    Ok(())
}
fn normalized(text: &str) -> String {
    text.replace("\r\n", "\n").replace('\r', "\n")
}
fn numeric(body: &str) -> Result<Option<u32>, String> {
    let Some(number) = body.strip_prefix('#') else {
        return Ok(None);
    };
    let (digits, radix) = number.strip_prefix('x').map_or((number, 10), |n| (n, 16));
    if digits.is_empty()
        || !digits.chars().all(|c| {
            if radix == 16 {
                c.is_ascii_hexdigit()
            } else {
                c.is_ascii_digit()
            }
        })
    {
        return Err(error());
    }
    let trimmed = digits.trim_start_matches('0');
    let cp = u32::from_str_radix(if trimmed.is_empty() { "0" } else { trimmed }, radix)
        .ok()
        .filter(|&cp| cp <= 0x10ffff)
        .ok_or_else(error)?;
    Ok(Some(cp))
}
// Shared representation with office_text's pre-parser UTF-16 transport.
// This handles references produced later by DTD expansion, after its first pass.
fn numeric_text(cp: u32) -> String {
    if cp == 0xe000 {
        "\u{e000}\u{e000}".into()
    } else if matches!(cp,0..=8|11..=12|14..=31|0xd800..=0xdfff|0xfffe..=0xffff) {
        format!("\u{e000}x{cp:X};")
    } else {
        char::from_u32(cp).unwrap().to_string()
    }
}
fn xml_name(name: &str) -> bool {
    let first = |c: char| matches!(c as u32,58|65..=90|95|97..=122|0xc0..=0xd6|0xd8..=0xf6|0xf8..=0x2ff|0x370..=0x37d|0x37f..=0x1fff|0x200c..=0x200d|0x2070..=0x218f|0x2c00..=0x2fef|0x3001..=0xd7ff|0xf900..=0xfdcf|0xfdf0..=0xfffd|0x10000..=0xeffff);
    let mut chars = name.chars();
    chars.next().is_some_and(first)
        && chars.all(|c| {
            first(c) || matches!(c as u32,45|46|48..=57|0xb7|0x300..=0x36f|0x203f..=0x2040)
        })
}
// Declaration-time numeric references become literal UTF-16 units in the
// replacement. .NET checks these units only when the entity is used: a direct
// unpaired surrogate/control fails, whereas a numeric reference generated by
// &#38; is interpreted later and retains the legacy numeric-reference behavior.
fn validate_entity_units(value: &str) -> Result<(), String> {
    let mut units = Vec::new();
    let mut rest = value;
    while !rest.is_empty() {
        if let Some(after) = rest.strip_prefix('\u{e000}') {
            if let Some(after) = after.strip_prefix('\u{e000}') {
                units.push(0xe000);
                rest = after;
                continue;
            }
            if let Some(code) = after.strip_prefix('x').and_then(|s| s.split_once(';'))
                && let Ok(unit) = u16::from_str_radix(code.0, 16)
            {
                units.push(unit);
                rest = code.1;
                continue;
            }
        }
        let c = rest.chars().next().unwrap();
        let mut buffer = [0; 2];
        units.extend_from_slice(c.encode_utf16(&mut buffer));
        rest = &rest[c.len_utf8()..];
    }
    let mut at = 0;
    while at < units.len() {
        let unit = units[at];
        if (0xd800..=0xdbff).contains(&unit) {
            if !units
                .get(at + 1)
                .is_some_and(|u| (0xdc00..=0xdfff).contains(u))
            {
                return Err("XML 엔티티에 짝 없는 UTF-16 문자가 있습니다.".into());
            }
            at += 2;
        } else {
            if (0xdc00..=0xdfff).contains(&unit) || !valid(char::from_u32(u32::from(unit)).unwrap())
            {
                return Err("XML 엔티티에 잘못된 문자가 있습니다.".into());
            }
            at += 1;
        }
    }
    Ok(())
}
// Numeric references in an entity declaration are interpreted at declaration
// time; named references remain references until that entity is used.
fn entity_value(text: &str) -> Result<String, String> {
    let text = normalized(text);
    let mut out = String::new();
    let mut at = 0;
    while let Some(offset) = text[at..].find('&') {
        let begin = at + offset;
        append(&mut out, &text[at..begin])?;
        let end = text[begin..]
            .find(';')
            .map(|i| begin + i)
            .ok_or_else(error)?;
        if let Some(cp) = numeric(&text[begin + 1..end])? {
            append(&mut out, &numeric_text(cp))?;
        } else {
            append(&mut out, &text[begin..=end])?;
        }
        at = end + 1;
    }
    append(&mut out, &text[at..])?;
    Ok(out)
}
struct Cursor<'a> {
    text: &'a str,
    at: usize,
}
impl<'a> Cursor<'a> {
    fn new(text: &'a str) -> Self {
        Self { text, at: 0 }
    }
    fn ws(&mut self) {
        while let Some(c) = self.text[self.at..].chars().next().filter(|&c| space(c)) {
            self.at += c.len_utf8();
        }
    }
    fn rest(&mut self) -> &'a str {
        self.ws();
        &self.text[self.at..]
    }
    fn word(&mut self) -> Result<&'a str, String> {
        self.ws();
        let start = self.at;
        while let Some(c) = self.text[self.at..].chars().next().filter(|&c| {
            !space(c) && !matches!(c, '(' | ')' | '\'' | '"' | '=' | '>' | '<' | '|' | '/')
        }) {
            self.at += c.len_utf8();
        }
        if self.at == start {
            Err(error())
        } else {
            Ok(&self.text[start..self.at])
        }
    }
    fn quoted(&mut self) -> Result<&'a str, String> {
        self.ws();
        let quote = self
            .text
            .as_bytes()
            .get(self.at)
            .copied()
            .filter(|c| matches!(c, b'\'' | b'"'))
            .ok_or_else(error)?;
        self.at += 1;
        let start = self.at;
        let end = self.text[start..]
            .find(quote as char)
            .map(|i| start + i)
            .ok_or_else(error)?;
        self.at = end + 1;
        Ok(&self.text[start..end])
    }
    fn group(&mut self) -> Result<(), String> {
        self.ws();
        if !self.text[self.at..].starts_with('(') {
            return Err(error());
        }
        let end = self.text[self.at..].find(')').ok_or_else(error)?;
        self.at += end + 1;
        Ok(())
    }
}
#[derive(Clone)]
enum Entity {
    Internal(String),
    External,
    Unparsed,
}
#[derive(Clone)]
struct Attribute {
    element: String,
    name: String,
    cdata: bool,
    default: Option<String>,
}
#[derive(Default)]
struct Dtd {
    entities: HashMap<String, Entity>,
    parameters: HashMap<String, Entity>,
    attributes: Vec<Attribute>,
    references: usize,
}
impl Dtd {
    fn reference(&mut self, depth: usize) -> Result<(), String> {
        self.references += 1;
        if self.references > REFERENCES || depth > DEPTH {
            Err("XML 엔티티 재귀·참조 한도를 넘었습니다.".into())
        } else {
            Ok(())
        }
    }
    fn subset(&mut self, text: &str, stack: &mut Vec<String>) -> Result<String, String> {
        let mut out = String::new();
        let mut at = 0;
        while at < text.len() {
            if text[at..].chars().next().is_some_and(space) {
                let c = text[at..].chars().next().unwrap();
                out.push(c);
                at += c.len_utf8();
                continue;
            }
            if text[at..].starts_with("<!--") {
                let end = text[at + 4..]
                    .find("-->")
                    .map(|i| at + 4 + i + 3)
                    .ok_or_else(error)?;
                append(&mut out, &text[at..end])?;
                at = end;
                continue;
            }
            if text[at..].starts_with("<?") {
                let end = text[at + 2..]
                    .find("?>")
                    .map(|i| at + 2 + i + 2)
                    .ok_or_else(error)?;
                append(&mut out, &text[at..end])?;
                at = end;
                continue;
            }
            if text[at..].starts_with('%') {
                let end = text[at..].find(';').map(|i| at + i).ok_or_else(error)?;
                let name = &text[at + 1..end];
                self.reference(stack.len())?;
                if stack.iter().any(|n| n == name) {
                    return Err("순환 XML 엔티티입니다.".into());
                }
                let entity = self.parameters.get(name).cloned().ok_or_else(error)?;
                if let Entity::Internal(value) = entity {
                    validate_entity_units(&value)?;
                    stack.push(name.into());
                    let expanded = self.subset(&value, stack)?;
                    stack.pop();
                    append(&mut out, &expanded)?;
                }
                at = end + 1;
                continue;
            }
            if !text[at..].starts_with("<!") {
                return Err(error());
            }
            let end = tag_end(text, at, false)?;
            let declaration = &text[at..=end];
            if let Some(body) = declaration.strip_prefix("<!ENTITY") {
                if !body.chars().next().is_some_and(space) {
                    return Err(error());
                }
                let mut cursor = Cursor::new(&body[..body.len() - 1]);
                let parameter = cursor.rest().starts_with('%');
                if parameter {
                    cursor.at += 1;
                    if !cursor.text[cursor.at..].chars().next().is_some_and(space) {
                        return Err(error());
                    }
                }
                let name = cursor.word()?.to_owned();
                if !xml_name(&name) {
                    return Err(error());
                }
                let value = if cursor.rest().starts_with(['\'', '"']) {
                    Entity::Internal(entity_value(cursor.quoted()?)?)
                } else {
                    let kind = cursor.word()?;
                    match kind {
                        "SYSTEM" => {
                            cursor.quoted()?;
                        }
                        "PUBLIC" => {
                            cursor.quoted()?;
                            cursor.quoted()?;
                        }
                        _ => return Err(error()),
                    }
                    if cursor.rest().starts_with("NDATA") {
                        cursor.word()?;
                        cursor.word()?;
                        Entity::Unparsed
                    } else {
                        Entity::External
                    }
                };
                if !cursor.rest().is_empty() {
                    return Err(error());
                }
                if parameter {
                    self.parameters.entry(name).or_insert(value);
                } else {
                    if matches!(&value, Entity::External | Entity::Unparsed) {
                        append(&mut out, &format!("<!ENTITY {name} ''>"))?;
                    } else {
                        append(&mut out, declaration)?;
                    }
                    self.entities.entry(name).or_insert(value);
                }
            } else if let Some(body) = declaration.strip_prefix("<!ATTLIST") {
                if !body.chars().next().is_some_and(space) {
                    return Err(error());
                }
                let mut c = Cursor::new(&body[..body.len() - 1]);
                let element = c.word()?.to_owned();
                while !c.rest().is_empty() {
                    let name = c.word()?.to_owned();
                    let enumeration = c.rest().starts_with('(');
                    let cdata;
                    if enumeration {
                        c.group()?;
                        cdata = false;
                    } else {
                        let ty = c.word()?;
                        cdata = ty == "CDATA";
                        if ty == "NOTATION" {
                            c.group()?;
                        } else if !matches!(
                            ty,
                            "CDATA"
                                | "ID"
                                | "IDREF"
                                | "IDREFS"
                                | "ENTITY"
                                | "ENTITIES"
                                | "NMTOKEN"
                                | "NMTOKENS"
                        ) {
                            return Err(error());
                        }
                    }
                    if name == "xml:space" && !enumeration {
                        return Err("xml:space DTD 속성에는 열거형 선언이 필요합니다.".into());
                    }
                    let default = if c.rest().starts_with('#') {
                        match c.word()? {
                            "#IMPLIED" | "#REQUIRED" => None,
                            "#FIXED" => Some(c.quoted()?.into()),
                            _ => return Err(error()),
                        }
                    } else {
                        Some(c.quoted()?.into())
                    };
                    if !self
                        .attributes
                        .iter()
                        .any(|a| a.element == element && a.name == name)
                    {
                        self.attributes.push(Attribute {
                            element: element.clone(),
                            name,
                            cdata,
                            default,
                        });
                    }
                }
                append(&mut out, declaration)?;
            } else if declaration.starts_with("<!ELEMENT") || declaration.starts_with("<!NOTATION")
            {
                append(&mut out, declaration)?;
            } else {
                return Err(error());
            }
            at = end + 1;
        }
        Ok(out)
    }
    fn attribute_value(
        &mut self,
        value: &str,
        cdata: bool,
        stack: &mut Vec<String>,
    ) -> Result<String, String> {
        let value = normalized(value);
        let mut out = String::new();
        let mut at = 0;
        while at < value.len() {
            let c = value[at..].chars().next().unwrap();
            if c == '<' {
                return Err("XML 속성 안에 마크업이 있습니다.".into());
            }
            if c != '&' {
                out.push(if space(c) { ' ' } else { c });
                at += c.len_utf8();
                continue;
            }
            let end = value[at..].find(';').map(|i| at + i).ok_or_else(error)?;
            let name = &value[at + 1..end];
            if let Some(cp) = numeric(name)? {
                append(&mut out, &numeric_text(cp))?;
            } else if let Some(c) = predefined(name) {
                out.push(c);
            } else {
                self.reference(stack.len())?;
                if stack.iter().any(|n| n == name) {
                    return Err("순환 XML 엔티티입니다.".into());
                }
                match self.entities.get(name).cloned().ok_or_else(error)? {
                    Entity::Internal(replacement) => {
                        validate_entity_units(&replacement)?;
                        stack.push(name.into());
                        let expanded = self.attribute_value(&replacement, true, stack)?;
                        stack.pop();
                        append(&mut out, &expanded)?;
                    }
                    _ => return Err("외부 XML 엔티티는 속성에서 사용할 수 없습니다.".into()),
                }
            }
            at = end + 1;
        }
        if !cdata {
            out = out
                .split(space)
                .filter(|s| !s.is_empty())
                .collect::<Vec<_>>()
                .join(" ");
        }
        Ok(out)
    }
    fn opening(&mut self, tag: &str) -> Result<String, String> {
        let self_closing = tag.ends_with("/>");
        let body = &tag[1..tag.len() - if self_closing { 2 } else { 1 }];
        if body.chars().next().is_some_and(space) {
            return Err(error());
        }
        let mut c = Cursor::new(body);
        let name = c.word()?.to_owned();
        let declarations: Vec<_> = self
            .attributes
            .iter()
            .filter(|a| a.element == name)
            .cloned()
            .collect();
        let mut attrs = Vec::new();
        let mut names = HashSet::new();
        loop {
            let before = c.at;
            c.ws();
            if c.at == c.text.len() {
                break;
            }
            if c.at == before {
                return Err(error());
            }
            let key = c.word()?.to_owned();
            if !names.insert(key.clone()) {
                return Err(error());
            }
            c.ws();
            if !c.text[c.at..].starts_with('=') {
                return Err(error());
            }
            c.at += 1;
            let raw = c.quoted()?;
            let cdata = declarations
                .iter()
                .find(|a| a.name == key)
                .is_none_or(|a| a.cdata);
            let value = self.attribute_value(raw, cdata, &mut Vec::new())?;
            attrs.push((key, value));
        }
        for declaration in declarations {
            if !names.contains(&declaration.name)
                && let Some(value) = declaration.default
            {
                attrs.push((
                    declaration.name,
                    self.attribute_value(&value, declaration.cdata, &mut Vec::new())?,
                ));
            }
        }
        let mut out = format!("<{name}");
        for (key, value) in attrs {
            append(
                &mut out,
                &format!(" {key}=\"{}\"", escape_attribute(&value)),
            )?;
        }
        out.push_str(if self_closing { "/>" } else { ">" });
        Ok(out)
    }
    fn content(&mut self, text: &str, entity_stack: &mut Vec<String>) -> Result<String, String> {
        let mut out = String::new();
        let mut at = 0;
        let mut elements: Vec<String> = Vec::new();
        while at < text.len() {
            if text[at..].starts_with('&') {
                let end = text[at..].find(';').map(|i| at + i).ok_or_else(error)?;
                let name = &text[at + 1..end];
                if let Some(cp) = numeric(name)?
                    && matches!(cp,0..=8|11..=12|14..=31|0xd800..=0xdfff|0xe000|0xfffe..=0xffff)
                {
                    append(&mut out, &numeric_text(cp))?;
                } else if name.starts_with('#') || predefined(name).is_some() {
                    append(&mut out, &text[at..=end])?;
                } else {
                    self.reference(entity_stack.len())?;
                    if entity_stack.iter().any(|n| n == name) {
                        return Err("순환 XML 엔티티입니다.".into());
                    }
                    match self.entities.get(name).cloned().ok_or_else(error)? {
                        Entity::Internal(value) => {
                            validate_entity_units(&value)?;
                            entity_stack.push(name.into());
                            let expanded = self.content(&value, entity_stack)?;
                            entity_stack.pop();
                            append(&mut out, &expanded)?;
                        }
                        Entity::External => {}
                        Entity::Unparsed => {
                            return Err("해석하지 않는 XML 엔티티를 본문에서 참조했습니다.".into());
                        }
                    }
                }
                at = end + 1;
                continue;
            }
            if text[at..].starts_with('<') {
                let rest = &text[at..];
                let special = if rest.starts_with("<!--") {
                    Some((4, "-->"))
                } else if rest.starts_with("<![CDATA[") {
                    Some((9, "]]>"))
                } else if rest.starts_with("<?") {
                    Some((2, "?>"))
                } else {
                    None
                };
                if let Some((offset, ending)) = special {
                    let end =
                        at + offset + rest[offset..].find(ending).ok_or_else(error)? + ending.len();
                    if !entity_stack.is_empty() && rest.starts_with("<![CDATA[") {
                        // The caller has already escaped literal U+E000. Reuse
                        // office_text's UTF-16 transport for CR introduced by
                        // a numeric reference in an entity declaration. A raw
                        // CR would be normalized by roxmltree; a character
                        // reference inside CDATA would remain literal text.
                        append(&mut out, &text[at..end].replace('\r', "\u{e000}xD;"))?;
                    } else {
                        append(&mut out, &text[at..end])?;
                    }
                    at = end;
                    continue;
                }
                let end = tag_end(text, at, false)?;
                let tag = &text[at..=end];
                if tag.starts_with("</") {
                    let name = tag[2..tag.len() - 1].trim_end_matches(space);
                    if elements.pop().as_deref() != Some(name) {
                        return Err("XML 엔티티의 태그 경계가 맞지 않습니다.".into());
                    }
                    append(&mut out, tag)?;
                } else if tag.starts_with("<!") {
                    return Err(error());
                } else {
                    let expanded = self.opening(tag)?;
                    if !tag.ends_with("/>") {
                        let mut c = Cursor::new(&tag[1..tag.len() - 1]);
                        elements.push(c.word()?.into());
                    }
                    append(&mut out, &expanded)?;
                }
                at = end + 1;
                continue;
            }
            let count = text[at..].find(['<', '&']).unwrap_or(text.len() - at);
            if entity_stack.is_empty() {
                append(&mut out, &text[at..at + count])?;
            } else {
                // Literal CR in a declaration was normalized before numeric
                // references were decoded, so remaining CR came from &#13;.
                append(&mut out, &text[at..at + count].replace('\r', "&#13;"))?;
            }
            at += count;
        }
        if !elements.is_empty() {
            return Err("XML 엔티티의 태그 경계가 맞지 않습니다.".into());
        }
        Ok(out)
    }
}
fn predefined(name: &str) -> Option<char> {
    match name {
        "amp" => Some('&'),
        "lt" => Some('<'),
        "gt" => Some('>'),
        "apos" => Some('\''),
        "quot" => Some('"'),
        _ => None,
    }
}
fn escape_attribute(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('"', "&quot;")
        .replace('\t', "&#9;")
        .replace('\n', "&#10;")
        .replace('\r', "&#13;")
}
fn tag_end(text: &str, start: usize, subset: bool) -> Result<usize, String> {
    let mut quote = None;
    let mut brackets = 0usize;
    let mut at = start + 1;
    while at < text.len() {
        if quote.is_none() && text.as_bytes()[at..].starts_with(b"<!--") {
            at += 4 + text[at + 4..].find("-->").ok_or_else(error)? + 3;
            continue;
        }
        let c = text.as_bytes()[at];
        if quote == Some(c) {
            quote = None;
        } else if quote.is_none() {
            match c {
                b'\'' | b'"' => quote = Some(c),
                b'[' if subset => brackets += 1,
                b']' if subset => brackets = brackets.saturating_sub(1),
                b'>' if brackets == 0 => return Ok(at),
                _ => {}
            }
        }
        at += 1;
    }
    Err(error())
}
/// Prepare only the PowerShell-compatible plain-text XML for its existing
/// roxmltree validation and whitespace stripping. No document is written.
/// The caller's lossless .NET UTF-16/control-reference transport runs first.
pub fn prepare_powershell_xml(xml: &str) -> Result<String, String> {
    if xml.len() > LIMIT {
        return Err("XML 크기 한도를 넘었습니다.".into());
    }
    let mut at = 0;
    let mut found = None;
    while let Some(i) = xml[at..].find('<').map(|i| at + i) {
        let rest = &xml[i..];
        if let Some(body) = rest.strip_prefix("<!--") {
            at = i + 4 + body.find("-->").ok_or_else(error)? + 3;
        } else if let Some(body) = rest.strip_prefix("<?") {
            at = i + 2 + body.find("?>").ok_or_else(error)? + 2;
        } else if rest.starts_with("<!DOCTYPE") {
            found = Some((i, tag_end(xml, i, true)?));
            break;
        } else {
            break;
        }
    }
    let Some((start, end)) = found else {
        return Ok(xml.into());
    };
    let declaration = &xml[start..=end];
    let mut quote = None;
    let mut bracket = None;
    for (i, c) in declaration.char_indices() {
        if quote == Some(c) {
            quote = None;
        } else if quote.is_none() {
            if matches!(c, '\'' | '"') {
                quote = Some(c);
            } else if c == '[' {
                bracket = Some(i);
                break;
            }
        }
    }
    let mut dtd = Dtd::default();
    let safe_declaration = if let Some(begin) = bracket {
        let finish = declaration.rfind(']').ok_or_else(error)?;
        let subset = dtd.subset(&declaration[begin + 1..finish], &mut Vec::new())?;
        format!(
            "{}[{}]{}",
            &declaration[..begin],
            subset,
            &declaration[finish + 1..]
        )
    } else {
        declaration.into()
    };
    // XmlDocument validates defaults even when the declared element is absent.
    for attribute in dtd.attributes.clone() {
        if let Some(value) = attribute.default {
            let value = dtd.attribute_value(&value, attribute.cdata, &mut Vec::new())?;
            if attribute.name == "xml:space" && !matches!(value.as_str(), "default" | "preserve") {
                return Err("잘못된 xml:space 기본값입니다.".into());
            }
        }
    }
    let body = dtd.content(&xml[end + 1..], &mut Vec::new())?;
    let mut result = String::new();
    append(&mut result, &xml[..start])?;
    append(&mut result, &safe_declaration)?;
    append(&mut result, &body)?;
    Ok(result)
}

#[cfg(test)]
mod tests {
    use super::*;
    fn parsed_text(xml: &str) -> String {
        let prepared = prepare_powershell_xml(xml).unwrap();
        let parsed = roxmltree::Document::parse_with_options(
            &prepared,
            roxmltree::ParsingOptions {
                allow_dtd: true,
                ..Default::default()
            },
        )
        .unwrap();
        parsed
            .descendants()
            .filter_map(|n| n.text().filter(|_| n.is_text()))
            .collect()
    }
    #[test]
    fn internal_whitespace_is_visible_but_cdata_and_escaped_refs_stay_distinct() {
        let xml = "<!DOCTYPE r [<!ENTITY s ' '><!ENTITY n '&#32;'><!ENTITY nested '&s;&n;'>]><r><t>&nested;</t><t><![CDATA[&s; ]]></t><t>&amp;s;</t></r>";
        let prepared = prepare_powershell_xml(xml).unwrap();
        assert!(prepared.contains("<t>  </t>"));
        assert!(prepared.contains("<![CDATA[&s; ]]>"));
        assert!(prepared.contains("<t>&amp;s;</t>"));
        assert_eq!(parsed_text(xml), "  &s; &s;");
    }
    #[test]
    fn numeric_entity_markup_is_expanded_but_predefined_lt_is_text() {
        let xml = "<!DOCTYPE r [<!ENTITY m '&#60;b>한😀&#60;/b>'><!ENTITY t '&lt;b>text&lt;/b>'><!ENTITY a '&#38;t;'>]><r>&m;&t;&a;</r>";
        let prepared = prepare_powershell_xml(xml).unwrap();
        assert!(prepared.contains("<r><b>한😀</b>&lt;b>text&lt;/b>&lt;b>text&lt;/b></r>"));
        assert_eq!(parsed_text(xml), "한😀<b>text</b><b>text</b>");
    }
    #[test]
    fn numeric_entity_cr_survives_reparse_in_text_and_cdata() {
        let text = "<!DOCTYPE r [<!ENTITY e '&#13;'>]><r xml:space='preserve'>A&e;B</r>";
        assert_eq!(parsed_text(text), "A\rB");
        let cdata = "<!DOCTYPE r [<!ENTITY e '<![CDATA[&#13;]]>'>]><r>&e;</r>";
        let prepared = prepare_powershell_xml(cdata).unwrap();
        assert!(prepared.contains("<r><![CDATA[\u{e000}xD;]]></r>"));
        // office_text restores this marker to the original CR after stripping.
        assert_eq!(parsed_text(cdata), "\u{e000}xD;");
        let literal = "<!DOCTYPE r [<!ENTITY e 'a\r\nb\rc'>]><r>&e;</r>";
        assert_eq!(parsed_text(literal), "a\nb\nc");
    }
    #[test]
    fn late_numeric_references_use_transport_without_decoding_literal_markers() {
        let marker = "<!DOCTYPE r [<!ENTITY e '&#38;#xE000;x41;'>]><r>&e;</r>";
        assert_eq!(parsed_text(marker), "\u{e000}\u{e000}x41;");
        let pair = "<!DOCTYPE r [<!ENTITY e '&#38;#55357;&#38;#56832;'>]><r>&e;</r>";
        assert_eq!(parsed_text(pair), "\u{e000}xD83D;\u{e000}xDE00;");
        let attribute = "<!DOCTYPE r [<!ENTITY e '&#38;#55357;'>]><r a='&e;'/>";
        let prepared = prepare_powershell_xml(attribute).unwrap();
        assert!(prepared.contains("a=\"\u{e000}xD83D;\""));
        let cdata = "<!DOCTYPE r [<!ENTITY e '<![CDATA[&#38;#55357;]]>'>]><r>&e;</r>";
        assert_eq!(parsed_text(cdata), "&#55357;");
    }
    #[test]
    fn declaration_time_surrogates_are_validated_only_when_entity_is_used() {
        // Values here mirror office_text's first transport pass.
        let high = "\u{e000}xD83D;";
        let low = "\u{e000}xDE00;";
        for value in [
            high.to_owned(),
            low.to_owned(),
            format!("{high}A{low}"),
            "\u{e000}x0;".into(),
        ] {
            let declaration = format!("<!DOCTYPE r [<!ENTITY e '{value}'>]>");
            assert!(prepare_powershell_xml(&format!("{declaration}<r>&e;</r>")).is_err());
            assert!(prepare_powershell_xml(&format!("{declaration}<r/>")).is_ok());
        }
        assert!(
            prepare_powershell_xml(&format!(
                "<!DOCTYPE r [<!ENTITY e '{high}{low}'>]><r>&e;</r>"
            ))
            .is_ok()
        );
        for bad in [
            "<!ENTITY %e '<!ENTITY a &#34;A&#34;>'>%e;",
            "<!ENTITY % 1 '<!ENTITY a &#34;A&#34;>'>%1;",
        ] {
            assert!(prepare_powershell_xml(&format!("<!DOCTYPE r [{bad}]><r>&a;</r>")).is_err());
        }
    }
    #[test]
    fn external_entities_are_empty_without_resolving_and_forbidden_in_attributes() {
        for external in [
            "SYSTEM 'file:///not-opened'",
            "PUBLIC 'public-id' 'https://not-opened.invalid/external'",
        ] {
            let xml = format!("<!DOCTYPE r [<!ENTITY ext {external}>]><r>A&ext;B</r>");
            assert_eq!(parsed_text(&xml), "AB");
            let xml = format!("<!DOCTYPE r [<!ENTITY ext {external}>]><r a='&ext;'/>");
            assert!(prepare_powershell_xml(&xml).is_err());
        }
        assert!(
            prepare_powershell_xml("<!DOCTYPE r [<!ENTITY ext SYSTEM 'x' NDATA png>]><r>&ext;</r>")
                .is_err()
        );
    }
    #[test]
    fn defaults_preserve_xml_space_and_normalize_only_declared_token_attributes() {
        let xml = "<!DOCTYPE r [<!ENTITY v ' a   b '><!ATTLIST r xml:space (default|preserve) 'preserve' a NMTOKENS '&v;' b CDATA 'x&#9;y'><!ATTLIST t a NMTOKENS #IMPLIED>]><r><t a=' a   b '/> </r>";
        let prepared = prepare_powershell_xml(xml).unwrap();
        let parsed = roxmltree::Document::parse_with_options(
            &prepared,
            roxmltree::ParsingOptions {
                allow_dtd: true,
                ..Default::default()
            },
        )
        .unwrap();
        let root = parsed.root_element();
        assert_eq!(
            root.attribute(("http://www.w3.org/XML/1998/namespace", "space")),
            Some("preserve")
        );
        assert_eq!(root.attribute("a"), Some("a b"));
        assert_eq!(root.attribute("b"), Some("x\ty"));
        assert_eq!(
            root.first_element_child().unwrap().attribute("a"),
            Some("a b")
        );
        let explicit=prepare_powershell_xml("<!DOCTYPE r [<!ATTLIST r xml:space (default|preserve) 'preserve'>]><r xml:space='default'/>").unwrap();
        assert!(explicit.contains("<r xml:space=\"default\"/>"));
        for decl in [
            "xml:space CDATA #IMPLIED",
            "xml:space CDATA 'preserve'",
            "xml:space (default|preserve) 'wrong'",
        ] {
            assert!(
                prepare_powershell_xml(&format!("<!DOCTYPE r [<!ATTLIST unused {decl}>]><r/>"))
                    .is_err()
            );
        }
    }
    #[test]
    fn parameter_subset_defaults_and_entity_fragment_defaults_are_applied() {
        let xml = "<!DOCTYPE r [<!ENTITY % defaults \"<!ATTLIST t xml:space (default|preserve) 'preserve'>\">%defaults;<!ENTITY content '<t> </t>'>]><r>&content;</r>";
        let prepared = prepare_powershell_xml(xml).unwrap();
        assert!(prepared.contains("<r><t xml:space=\"preserve\"> </t></r>"));
        assert!(!prepared.contains("%defaults;"));
        assert_eq!(parsed_text(xml), " ");
    }
    #[test]
    fn cycles_exponential_expansion_and_cross_entity_tags_fail() {
        for xml in [
            "<!DOCTYPE r [<!ENTITY x '&x;'>]><r>&x;</r>",
            "<!DOCTYPE r [<!ENTITY a '&b;'><!ENTITY b '&a;'>]><r>&a;</r>",
            "<!DOCTYPE r [<!ENTITY a '<x>'><!ENTITY b '</x>'>]><r>&a;&b;</r>",
            "<!DOCTYPE r []><r a='1'b='2'/>",
        ] {
            assert!(prepare_powershell_xml(xml).is_err());
        }
        let mut xml = String::from("<!DOCTYPE r [<!ENTITY e0 'a'>");
        for i in 1..=18 {
            xml.push_str(&format!("<!ENTITY e{i} '&e{};&e{};'>", i - 1, i - 1));
        }
        xml.push_str("]><r>&e18;</r>");
        assert!(prepare_powershell_xml(&xml).is_err());
    }
}
